namespace RevitShortcuts.Services
{
    /// <summary>
    /// Service for exporting QA reports in multiple formats
    /// </summary>
    public class ReportExportService
    {
        private readonly Document _doc;
        private readonly ModelHealthSummary _summary;

        public ReportExportService(Document doc, ModelHealthSummary summary)
        {
            _doc = doc;
            _summary = summary;

            // Set EPPlus license context
            ExcelPackage.LicenseContext = LicenseContext.NonCommercial;
        }

        #region Excel Export

        public void ExportToExcel(string filePath)
        {
            using (var package = new ExcelPackage())
            {
                // Summary sheet
                CreateSummarySheet(package);

                // Detailed findings sheet
                CreateDetailedFindingsSheet(package);

                // Issues by category
                CreateCategoryBreakdownSheet(package);

                // Element list (for affected elements)
                CreateAffectedElementsSheet(package);

                // Metrics sheet
                CreateMetricsSheet(package);

                package.SaveAs(new FileInfo(filePath));
            }
        }

        private void CreateSummarySheet(ExcelPackage package)
        {
            var worksheet = package.Workbook.Worksheets.Add("Summary");

            // Header
            worksheet.Cells["A1"].Value = "Model Health Report - Summary";
            worksheet.Cells["A1:F1"].Merge = true;
            worksheet.Cells["A1"].Style.Font.Size = 18;
            worksheet.Cells["A1"].Style.Font.Bold = true;
            worksheet.Cells["A1"].Style.HorizontalAlignment = ExcelHorizontalAlignment.Center;

            int row = 3;

            // Project Info
            worksheet.Cells[row, 1].Value = "Project Information";
            worksheet.Cells[row, 1].Style.Font.Bold = true;
            worksheet.Cells[row, 1].Style.Font.Size = 14;
            row += 2;

            worksheet.Cells[row, 1].Value = "Project Name:";
            worksheet.Cells[row, 2].Value = _summary.ProjectName;
            row++;

            worksheet.Cells[row, 1].Value = "File Path:";
            worksheet.Cells[row, 2].Value = _summary.FilePath;
            row++;

            worksheet.Cells[row, 1].Value = "File Size (MB):";
            worksheet.Cells[row, 2].Value = _summary.FileSizeMB;
            worksheet.Cells[row, 2].Style.Numberformat.Format = "#,##0.00";
            row++;

            worksheet.Cells[row, 1].Value = "Generated Date:";
            worksheet.Cells[row, 2].Value = _summary.GeneratedDate;
            worksheet.Cells[row, 2].Style.Numberformat.Format = "yyyy-mm-dd hh:mm:ss";
            row++;

            worksheet.Cells[row, 1].Value = "Generated By:";
            worksheet.Cells[row, 2].Value = _summary.GeneratedBy;
            row += 2;

            // Quality Score
            worksheet.Cells[row, 1].Value = "Quality Score";
            worksheet.Cells[row, 1].Style.Font.Bold = true;
            worksheet.Cells[row, 1].Style.Font.Size = 14;
            row += 2;

            worksheet.Cells[row, 1].Value = "Overall Score:";
            worksheet.Cells[row, 2].Value = _summary.OverallQualityScore;
            worksheet.Cells[row, 2].Style.Numberformat.Format = "0.00";
            worksheet.Cells[row, 2].Style.Font.Size = 16;
            worksheet.Cells[row, 2].Style.Font.Bold = true;
            row++;

            worksheet.Cells[row, 1].Value = "Grade:";
            worksheet.Cells[row, 2].Value = _summary.QualityGrade;
            worksheet.Cells[row, 2].Style.Font.Size = 16;
            worksheet.Cells[row, 2].Style.Font.Bold = true;
            SetGradeColor(worksheet.Cells[row, 2], _summary.QualityGrade);
            row += 2;

            // Statistics
            worksheet.Cells[row, 1].Value = "Check Statistics";
            worksheet.Cells[row, 1].Style.Font.Bold = true;
            worksheet.Cells[row, 1].Style.Font.Size = 14;
            row += 2;

            var stats = new Dictionary<string, int>
            {
                { "Total Checks", _summary.TotalChecks },
                { "Passed", _summary.PassedChecks },
                { "Failed", _summary.FailedChecks },
                { "Total Issues", _summary.TotalIssues },
                { "Critical Issues", _summary.CriticalIssues },
                { "Errors", _summary.ErrorIssues },
                { "Warnings", _summary.WarningIssues },
                { "Info", _summary.InfoIssues }
            };

            foreach (var stat in stats)
            {
                worksheet.Cells[row, 1].Value = stat.Key + ":";
                worksheet.Cells[row, 2].Value = stat.Value;
                row++;
            }

            row += 2;

            // Model Metrics
            worksheet.Cells[row, 1].Value = "Model Metrics";
            worksheet.Cells[row, 1].Style.Font.Bold = true;
            worksheet.Cells[row, 1].Style.Font.Size = 14;
            row += 2;

            var metrics = new Dictionary<string, int>
            {
                { "Total Elements", _summary.TotalElements },
                { "Total Views", _summary.TotalViews },
                { "Total Sheets", _summary.TotalSheets },
                { "Total Families", _summary.TotalFamilies },
                { "Total Warnings", _summary.TotalWarnings }
            };

            foreach (var metric in metrics)
            {
                worksheet.Cells[row, 1].Value = metric.Key + ":";
                worksheet.Cells[row, 2].Value = metric.Value;
                worksheet.Cells[row, 2].Style.Numberformat.Format = "#,##0";
                row++;
            }

            worksheet.Cells.AutoFitColumns();
        }

        private void CreateDetailedFindingsSheet(ExcelPackage package)
        {
            var worksheet = package.Workbook.Worksheets.Add("Detailed Findings");

            // Headers
            worksheet.Cells[1, 1].Value = "Category";
            worksheet.Cells[1, 2].Value = "Check Name";
            worksheet.Cells[1, 3].Value = "Status";
            worksheet.Cells[1, 4].Value = "Severity";
            worksheet.Cells[1, 5].Value = "Issue Count";
            worksheet.Cells[1, 6].Value = "Message";
            worksheet.Cells[1, 7].Value = "Details";
            worksheet.Cells[1, 8].Value = "Recommended Fix";

            // Style headers
            using (var range = worksheet.Cells[1, 1, 1, 8])
            {
                range.Style.Font.Bold = true;
                range.Style.Fill.PatternType = ExcelFillStyle.Solid;
                range.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(79, 129, 189));
                range.Style.Font.Color.SetColor(System.Drawing.Color.White);
            }

            int row = 2;

            foreach (var category in _summary.Categories)
            {
                foreach (var result in category.Results)
                {
                    worksheet.Cells[row, 1].Value = category.CategoryName;
                    worksheet.Cells[row, 2].Value = result.CheckName;
                    worksheet.Cells[row, 3].Value = result.Passed ? "PASS" : "FAIL";
                    worksheet.Cells[row, 4].Value = result.Severity.ToString();
                    worksheet.Cells[row, 5].Value = result.IssueCount;
                    worksheet.Cells[row, 6].Value = result.Message;
                    worksheet.Cells[row, 7].Value = result.Details;
                    worksheet.Cells[row, 8].Value = result.RecommendedFix;

                    // Color code status
                    if (!result.Passed)
                    {
                        worksheet.Cells[row, 3].Style.Fill.PatternType = ExcelFillStyle.Solid;
                        worksheet.Cells[row, 3].Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(255, 199, 206));
                    }
                    else
                    {
                        worksheet.Cells[row, 3].Style.Fill.PatternType = ExcelFillStyle.Solid;
                        worksheet.Cells[row, 3].Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(198, 239, 206));
                    }

                    row++;
                }
            }

            worksheet.Cells.AutoFitColumns();
        }

        private void CreateCategoryBreakdownSheet(ExcelPackage package)
        {
            var worksheet = package.Workbook.Worksheets.Add("Category Breakdown");

            // Headers
            worksheet.Cells[1, 1].Value = "Category";
            worksheet.Cells[1, 2].Value = "Total Checks";
            worksheet.Cells[1, 3].Value = "Passed";
            worksheet.Cells[1, 4].Value = "Failed";
            worksheet.Cells[1, 5].Value = "Total Issues";
            worksheet.Cells[1, 6].Value = "Pass Rate %";

            // Style headers
            using (var range = worksheet.Cells[1, 1, 1, 6])
            {
                range.Style.Font.Bold = true;
                range.Style.Fill.PatternType = ExcelFillStyle.Solid;
                range.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(79, 129, 189));
                range.Style.Font.Color.SetColor(System.Drawing.Color.White);
            }

            int row = 2;

            foreach (var category in _summary.Categories)
            {
                int totalChecks = category.Results.Count;
                double passRate = totalChecks > 0 ? (double)category.PassedCount / totalChecks * 100 : 0;

                worksheet.Cells[row, 1].Value = category.CategoryName;
                worksheet.Cells[row, 2].Value = totalChecks;
                worksheet.Cells[row, 3].Value = category.PassedCount;
                worksheet.Cells[row, 4].Value = category.FailedCount;
                worksheet.Cells[row, 5].Value = category.TotalIssues;
                worksheet.Cells[row, 6].Value = passRate;
                worksheet.Cells[row, 6].Style.Numberformat.Format = "0.00";

                row++;
            }

            worksheet.Cells.AutoFitColumns();
        }

        private void CreateAffectedElementsSheet(ExcelPackage package)
        {
            var worksheet = package.Workbook.Worksheets.Add("Affected Elements");

            // Headers
            worksheet.Cells[1, 1].Value = "Category";
            worksheet.Cells[1, 2].Value = "Check Name";
            worksheet.Cells[1, 3].Value = "Element IDs";

            using (var range = worksheet.Cells[1, 1, 1, 3])
            {
                range.Style.Font.Bold = true;
                range.Style.Fill.PatternType = ExcelFillStyle.Solid;
                range.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(79, 129, 189));
                range.Style.Font.Color.SetColor(System.Drawing.Color.White);
            }

            int row = 2;

            foreach (var category in _summary.Categories)
            {
                foreach (var result in category.Results.Where(r => r.AffectedElements?.Count > 0))
                {
                    worksheet.Cells[row, 1].Value = category.CategoryName;
                    worksheet.Cells[row, 2].Value = result.CheckName;
                    worksheet.Cells[row, 3].Value = string.Join(", ", result.AffectedElements.Select(id => id.IntegerValue));
                    row++;
                }
            }

            worksheet.Cells.AutoFitColumns();
        }

        private void CreateMetricsSheet(ExcelPackage package)
        {
            var worksheet = package.Workbook.Worksheets.Add("Metrics");

            worksheet.Cells[1, 1].Value = "Check Name";
            worksheet.Cells[1, 2].Value = "Metric Key";
            worksheet.Cells[1, 3].Value = "Metric Value";

            using (var range = worksheet.Cells[1, 1, 1, 3])
            {
                range.Style.Font.Bold = true;
                range.Style.Fill.PatternType = ExcelFillStyle.Solid;
                range.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(79, 129, 189));
                range.Style.Font.Color.SetColor(System.Drawing.Color.White);
            }

            int row = 2;

            foreach (var category in _summary.Categories)
            {
                foreach (var result in category.Results.Where(r => r.Metrics?.Count > 0))
                {
                    foreach (var metric in result.Metrics)
                    {
                        worksheet.Cells[row, 1].Value = result.CheckName;
                        worksheet.Cells[row, 2].Value = metric.Key;
                        worksheet.Cells[row, 3].Value = metric.Value?.ToString();
                        row++;
                    }
                }
            }

            worksheet.Cells.AutoFitColumns();
        }

        private void SetGradeColor(ExcelRange cell, string grade)
        {
            cell.Style.Fill.PatternType = ExcelFillStyle.Solid;
            switch (grade)
            {
                case "A":
                    cell.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(0, 176, 80));
                    cell.Style.Font.Color.SetColor(System.Drawing.Color.White);
                    break;
                case "B":
                    cell.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(146, 208, 80));
                    break;
                case "C":
                    cell.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(255, 217, 102));
                    break;
                case "D":
                    cell.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(255, 153, 0));
                    break;
                case "F":
                    cell.Style.Fill.BackgroundColor.SetColor(System.Drawing.Color.FromArgb(255, 0, 0));
                    cell.Style.Font.Color.SetColor(System.Drawing.Color.White);
                    break;
            }
        }

