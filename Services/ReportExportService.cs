        #region BCF Export

        public void ExportToBCF(string filePath)
        {
            // BCF (BIM Collaboration Format) is a ZIP-based format
            // This is a simplified implementation - full BCF would require more detail

            string tempDir = Path.Combine(Path.GetTempPath(), Guid.NewGuid().ToString());
            Directory.CreateDirectory(tempDir);

            try
            {
                // Create BCF structure
                CreateBCFMarkup(tempDir);
                CreateBCFProject(tempDir);

                // Create issues for failed checks
                int issueIndex = 1;
                foreach (var category in _summary.Categories)
                {
                    foreach (var result in category.Results.Where(r => !r.Passed))
                    {
                        CreateBCFIssue(tempDir, result, category.CategoryName, issueIndex++);
                    }
                }

                // Zip the folder
                if (File.Exists(filePath))
                    File.Delete(filePath);

                ZipFile.CreateFromDirectory(tempDir, filePath);
            }
            finally
            {
                if (Directory.Exists(tempDir))
                    Directory.Delete(tempDir, true);
            }
        }

        private void CreateBCFProject(string tempDir)
        {
            var projectXml = $@"<?xml version=""1.0"" encoding=""UTF-8""?>
<ProjectExtension>
    <Project ProjectId=""{Guid.NewGuid()}"">
        <Name>{_summary.ProjectName}</Name>
    </Project>
</ProjectExtension>";

            File.WriteAllText(Path.Combine(tempDir, "project.bcfp"), projectXml);
        }

        private void CreateBCFMarkup(string tempDir)
        {
            var versionXml = @"<?xml version=""1.0"" encoding=""UTF-8""?>
<Version VersionId=""2.1"">
    <DetailedVersion>2.1</DetailedVersion>
</Version>";

            File.WriteAllText(Path.Combine(tempDir, "bcf.version"), versionXml);
        }

        private void CreateBCFIssue(string tempDir, QACheckResult result, string category, int index)
        {
            string issueGuid = Guid.NewGuid().ToString();
            string issueDir = Path.Combine(tempDir, issueGuid);
            Directory.CreateDirectory(issueDir);

            var markupXml = $@"<?xml version=""1.0"" encoding=""UTF-8""?>
<Markup>
    <Header>
        <File IfcProject=""{_doc.ProjectInformation.UniqueId}"" />
        <Date>{DateTime.Now:yyyy-MM-ddTHH:mm:ss}</Date>
        <Author>{_summary.GeneratedBy}</Author>
    </Header>
    <Topic Guid=""{issueGuid}"" TopicType=""{result.Severity}"">
        <Title>{result.CheckName}</Title>
        <Priority>{GetBCFPriority(result.Severity)}</Priority>
        <Index>{index}</Index>
        <Labels>{category}</Labels>
        <CreationDate>{DateTime.Now:yyyy-MM-ddTHH:mm:ss}</CreationDate>
        <CreationAuthor>{_summary.GeneratedBy}</CreationAuthor>
        <Description>{result.Message}</Description>
    </Topic>
    <Comment Guid=""{Guid.NewGuid()}"">
        <Date>{DateTime.Now:yyyy-MM-ddTHH:mm:ss}</Date>
        <Author>{_summary.GeneratedBy}</Author>
        <Comment>Issue Count: {result.IssueCount}</Comment>
    </Comment>";

            if (!string.IsNullOrEmpty(result.RecommendedFix))
            {
                markupXml += $@"
    <Comment Guid=""{Guid.NewGuid()}"">
        <Date>{DateTime.Now:yyyy-MM-ddTHH:mm:ss}</Date>
        <Author>System</Author>
        <Comment>Recommended Fix: {result.RecommendedFix}</Comment>
    </Comment>";
            }

            markupXml += "\n</Markup>";

            File.WriteAllText(Path.Combine(issueDir, "markup.bcf"), markupXml);
        }

        private string GetBCFPriority(IssueSeverity severity)
        {
            switch (severity)
            {
                case IssueSeverity.Critical:
                    return "Critical";
                case IssueSeverity.Error:
                    return "Major";
                case IssueSeverity.Warning:
                    return "Normal";
                case IssueSeverity.Info:
                    return "Minor";
                default:
                    return "Normal";
            }
        }

