        #region PDF Export

        public void ExportToPDF(string filePath)
        {
            Document pdfDoc = new Document(PageSize.A4);
            PdfWriter.GetInstance(pdfDoc, new FileStream(filePath, FileMode.Create));
            pdfDoc.Open();

            // Title
            var titleFont = FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 24);
            var title = new Paragraph("Model Health Report", titleFont);
            title.Alignment = Element.ALIGN_CENTER;
            pdfDoc.Add(title);

            pdfDoc.Add(new Paragraph("\n"));

            // Project Info
            var headerFont = FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 14);
            var normalFont = FontFactory.GetFont(FontFactory.HELVETICA, 10);

            pdfDoc.Add(new Paragraph("Project Information", headerFont));
            pdfDoc.Add(new Paragraph($"Project: {_summary.ProjectName}", normalFont));
            pdfDoc.Add(new Paragraph($"File Size: {_summary.FileSizeMB:F2} MB", normalFont));
            pdfDoc.Add(new Paragraph($"Date: {_summary.GeneratedDate:yyyy-MM-dd HH:mm:ss}", normalFont));
            pdfDoc.Add(new Paragraph($"Generated By: {_summary.GeneratedBy}", normalFont));
            pdfDoc.Add(new Paragraph("\n"));

            // Quality Score
            pdfDoc.Add(new Paragraph("Quality Score", headerFont));
            var scoreFont = FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 18);
            pdfDoc.Add(new Paragraph($"Score: {_summary.OverallQualityScore:F1} / 100 (Grade: {_summary.QualityGrade})", scoreFont));
            pdfDoc.Add(new Paragraph("\n"));

            // Summary Statistics
            pdfDoc.Add(new Paragraph("Summary Statistics", headerFont));
            PdfPTable statsTable = new PdfPTable(2);
            statsTable.WidthPercentage = 100;

            AddTableRow(statsTable, "Total Checks", _summary.TotalChecks.ToString());
            AddTableRow(statsTable, "Passed", _summary.PassedChecks.ToString());
            AddTableRow(statsTable, "Failed", _summary.FailedChecks.ToString());
            AddTableRow(statsTable, "Critical Issues", _summary.CriticalIssues.ToString());
            AddTableRow(statsTable, "Errors", _summary.ErrorIssues.ToString());
            AddTableRow(statsTable, "Warnings", _summary.WarningIssues.ToString());

            pdfDoc.Add(statsTable);
            pdfDoc.Add(new Paragraph("\n"));

            // Category Breakdown
            pdfDoc.Add(new Paragraph("Category Breakdown", headerFont));
            PdfPTable catTable = new PdfPTable(4);
            catTable.WidthPercentage = 100;

            // Headers
            AddTableCell(catTable, "Category", true);
            AddTableCell(catTable, "Passed", true);
            AddTableCell(catTable, "Failed", true);
            AddTableCell(catTable, "Issues", true);

            foreach (var category in _summary.Categories)
            {
                AddTableCell(catTable, category.CategoryName, false);
                AddTableCell(catTable, category.PassedCount.ToString(), false);
                AddTableCell(catTable, category.FailedCount.ToString(), false);
                AddTableCell(catTable, category.TotalIssues.ToString(), false);
            }

            pdfDoc.Add(catTable);
            pdfDoc.Add(new Paragraph("\n"));

            // Failed Checks Detail
            pdfDoc.Add(new Paragraph("Failed Checks - Details", headerFont));

            foreach (var category in _summary.Categories)
            {
                var failedChecks = category.Results.Where(r => !r.Passed).ToList();
                if (failedChecks.Any())
                {
                    pdfDoc.Add(new Paragraph($"\n{category.CategoryName}", FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 12)));

                    foreach (var check in failedChecks)
                    {
                        pdfDoc.Add(new Paragraph($"  • {check.CheckName} ({check.Severity})", normalFont));
                        pdfDoc.Add(new Paragraph($"    {check.Message}", normalFont));
                        if (!string.IsNullOrEmpty(check.RecommendedFix))
                        {
                            pdfDoc.Add(new Paragraph($"    Fix: {check.RecommendedFix}", FontFactory.GetFont(FontFactory.HELVETICA_OBLIQUE, 9)));
                        }
                    }
                }
            }

            pdfDoc.Close();
        }

        private void AddTableRow(PdfPTable table, string label, string value)
        {
            var cellLabel = new PdfPCell(new Phrase(label, FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 10)));
            cellLabel.Border = Rectangle.NO_BORDER;
            cellLabel.Padding = 5;
            table.AddCell(cellLabel);

            var cellValue = new PdfPCell(new Phrase(value, FontFactory.GetFont(FontFactory.HELVETICA, 10)));
            cellValue.Border = Rectangle.NO_BORDER;
            cellValue.Padding = 5;
            table.AddCell(cellValue);
        }

        private void AddTableCell(PdfPTable table, string text, bool isHeader)
        {
            var font = isHeader
                ? FontFactory.GetFont(FontFactory.HELVETICA_BOLD, 10)
                : FontFactory.GetFont(FontFactory.HELVETICA, 9);

            var cell = new PdfPCell(new Phrase(text, font));
            cell.Padding = 5;

            if (isHeader)
            {
                cell.BackgroundColor = new BaseColor(79, 129, 189);
                cell.HorizontalAlignment = Element.ALIGN_CENTER;
            }

            table.AddCell(cell);
        }

